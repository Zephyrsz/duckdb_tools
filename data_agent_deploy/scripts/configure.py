"""Create private local settings without replacing existing user configuration."""
from pathlib import Path
import os
import secrets

root = Path(__file__).resolve().parents[1]
target = root / ".env"
if not target.exists():
    text = (root / ".env.example").read_text()
    text = text.replace("RDS_API_TOKEN=\n", f"RDS_API_TOKEN={secrets.token_urlsafe(48)}\n")
    with os.fdopen(os.open(target, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600), "w") as stream:
        stream.write(text)
link = root / "openmuse" / ".env"
if not link.exists() and not link.is_symlink():
    link.symlink_to("../.env")
mobile = root / "openmuse/apps/mobile/.env"
if mobile.is_symlink() and mobile.readlink() == Path("../../../.env"):
    mobile.unlink()
marker = "# Generated by scripts/configure.py; public client settings only.\n"
if not mobile.exists() or mobile.read_text().startswith(marker):
    public = next((line for line in target.read_text().splitlines() if line.startswith("EXPO_PUBLIC_API_URL=")), "EXPO_PUBLIC_API_URL=http://localhost:8787")
    mobile.write_text(marker + public + "\n")
print("Local settings: data_agent_deploy/.env (credentials are not printed)")
